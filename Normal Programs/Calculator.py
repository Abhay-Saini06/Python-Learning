a = int(input("Enter the value 1 :"))
b = int(input("Enter the value 2 :"))
c = input("Enter the operation :")
if(c == "+"):
    print("The addition is ",a+b)
elif(c == "-"):
    print("The subtraction is",a-b)
elif(c == "/"):
    print("The division is ",a/b)
elif(c == "%"):
    print("The remainder is ",a%b)